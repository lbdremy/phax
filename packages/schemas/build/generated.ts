// Pure renderers behind scripts/schemas-check.ts: the generated index the
// package reads its version and first supported release from, and the lock
// that pins every frozen module.
import { createHash } from "node:crypto";

export const WRITE_COMMAND = "pnpm exec tsx scripts/schemas-check.ts --write";

/** Source of `packages/schemas/src/generated/index.ts`. */
export function renderGeneratedIndex({
  packageVersion,
  firstSupportedRelease,
}: {
  packageVersion: string;
  firstSupportedRelease: string | null;
}): string {
  return [
    `// Generated by \`${WRITE_COMMAND}\` — do not edit.`,
    "// Mirrors the root package.json version, which the package names in its",
    "// upgrade messages and compares a document's $schema release against.",
    `export const PACKAGE_VERSION = ${JSON.stringify(packageVersion)} as const;`,
    "// The lowest release-named snapshot under packages/schemas/snapshots/, or",
    "// null while no release has written $schema yet.",
    `export const FIRST_SUPPORTED_RELEASE: string | null = ${JSON.stringify(firstSupportedRelease)};`,
    "",
  ].join("\n");
}

/** Repo-relative path → sha256 hex of the frozen module's bytes. */
export type HistoryLock = Readonly<Record<string, string>>;

export function sha256(bytes: string | Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

/**
 * Adds a lock entry for every history file that has none, and reports the
 * paths whose existing entry no longer matches their bytes. An existing entry
 * is never changed: a frozen module does not change once pinned.
 */
export function refreshLock(
  lock: HistoryLock,
  files: ReadonlyMap<string, string | Uint8Array>,
): { lock: HistoryLock; mismatched: ReadonlyArray<string> } {
  const next: Record<string, string> = { ...lock };
  const mismatched: string[] = [];
  for (const [path, bytes] of files) {
    const hash = sha256(bytes);
    const pinned = lock[path];
    if (pinned === undefined) next[path] = hash;
    else if (pinned !== hash) mismatched.push(path);
  }
  const sorted = Object.fromEntries(
    Object.entries(next).toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  );
  return { lock: sorted, mismatched: mismatched.toSorted() };
}

export function renderLock(lock: HistoryLock): string {
  return `${JSON.stringify(lock, null, 2)}\n`;
}
